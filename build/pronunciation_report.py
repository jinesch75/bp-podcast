#!/usr/bin/env python3
"""List every spoken sentence whose ElevenLabs text differs from the script (all episodes, EN/FR/DE).
Run from the project root:  python3 build/pronunciation_report.py  ->  build/pronunciation_report.md"""
import glob, os, re, sys, difflib, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pronunciation import spoken

def turns(path):
    for line in open(path, encoding="utf-8"):
        m = re.match(r"\*\*(ANNA|TOM)\s*:\*\*\s*(.*)", line.strip())
        if m:
            yield m.group(1).title(), m.group(2)

def sentences(t):
    t = t.replace("...", "<E>")
    return [p.replace("<E>", "...").strip() for p in re.split(r"(?<=[.!?])\s+", t) if p.strip()]

def changes(a, b):
    sa, sb = a.split(), b.split()
    out = []
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, sa, sb).get_opcodes():
        if op != "equal":
            out.append((" ".join(sa[i1:i2]) or "∅", " ".join(sb[j1:j2]) or "∅"))
    return out

keys = sorted(set(re.sub(r"_(fr|de|lb)$", "", os.path.basename(f)[15:-3]) for f in glob.glob("podcast_script_*.md")))
out = ["# Pronunciation report", "",
       "Generated by `build/pronunciation_report.py` from the rules in `build/pronunciation.py`.",
       "Only the text sent to ElevenLabs changes; transcripts on the site keep the written form.", ""]
summary = collections.Counter()
per_lang = collections.Counter()
body = []
for lang, suf in (("en", ""), ("fr", "_fr"), ("de", "_de")):
    body += ["", f"## {lang.upper()}", ""]
    for key in keys:
        path = f"podcast_script_{key}{suf}.md"
        if not os.path.exists(path):
            continue
        rows = []
        for spk, t in turns(path):
            for s in sentences(t):
                w = s.replace("**", "")
                sp = spoken(w, lang)
                if sp != w.strip():
                    ch = changes(w, sp)
                    for a, b in ch:
                        summary[(lang, a.strip(".,;:!?()«»\"“”„"), b.strip(".,;:!?()«»\"“”„"))] += 1
                    rows.append(f"- **{spk}:** {w}  \n  → {sp}")
        if rows:
            per_lang[lang] += len(rows)
            body += [f"### {key} ({len(rows)})", ""] + rows + [""]
out += ["## Summary", "", "| Language | Sentences changed |", "|---|---|"]
out += [f"| {l.upper()} | {per_lang[l]} |" for l in ("en", "fr", "de")]
out += ["", "## Most frequent changes", "", "| Lang | Written | Spoken | Count |", "|---|---|---|---|"]
for (l, a, b), c in summary.most_common():
    out.append(f"| {l.upper()} | {a} | {b} | {c} |")
open("build/pronunciation_report.md", "w", encoding="utf-8").write("\n".join(out + body) + "\n")
print("build/pronunciation_report.md:", dict(per_lang))
